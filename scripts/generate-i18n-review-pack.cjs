#!/usr/bin/env node
/**
 * Generator for the i18n native-language review pack (VF-20260918-P3-020).
 *
 * Walks src/i18n/resources/<locale>/<namespace>.json for each non-English
 * locale and emits:
 *   - docs/i18n/review-pack/PLACEHOLDER-INVENTORY.json
 *     (machine-readable: per-locale per-namespace placeholder list)
 *   - docs/i18n/review-pack/PER-LOCALE/<locale>.md
 *     (human-readable review instructions + the same list as a checklist)
 *
 * The generator NEVER modifies the first-pass machine-translation catalogs
 * in src/i18n/resources/. It only reads them and produces review-pack
 * artifacts. Human translators edit src/i18n/resources/<locale>/<ns>.json
 * directly (or via their tooling of choice) and the result is verified by
 * scripts/verify-i18n-review-status.cjs.
 *
 * Exit codes:
 *   0 = inventory + per-locale files generated and consistent
 *   1 = src/i18n resources are missing, malformed, or unreadable
 */

const fs = require("node:fs");
const path = require("node:path");

const REPO_ROOT = path.resolve(__dirname, "..");
const RESOURCES_ROOT = path.join(REPO_ROOT, "src/i18n/resources");
const REVIEW_PACK_ROOT = path.join(REPO_ROOT, "docs/i18n/review-pack");
const EN_US = "en-US";

function listLocales() {
  return fs
    .readdirSync(RESOURCES_ROOT)
    .filter((name) => fs.statSync(path.join(RESOURCES_ROOT, name)).isDirectory());
}

function listNamespaces(locale) {
  const localeDir = path.join(RESOURCES_ROOT, locale);
  return fs
    .readdirSync(localeDir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""));
}

function readJsonSafe(filePath) {
  try {
    return { ok: true, value: JSON.parse(fs.readFileSync(filePath, "utf8")) };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

/**
 * Walks a JSON document and yields { path, missing } entries for every leaf
 * whose value matches /__MISSING__:.../. Path uses dot-notation for objects
 * and bracket notation for arrays, matching the way i18n-key namespaces
 * are typically addressed.
 */
function findMissing(obj, currentPath = "") {
  const out = [];
  if (obj === null || obj === undefined) return out;
  if (typeof obj === "string") {
    if (obj.startsWith("__MISSING__:")) {
      out.push({ path: currentPath, marker: obj });
    }
    return out;
  }
  if (Array.isArray(obj)) {
    obj.forEach((v, i) => out.push(...findMissing(v, `${currentPath}[${i}]`)));
    return out;
  }
  if (typeof obj === "object") {
    for (const [k, v] of Object.entries(obj)) {
      out.push(...findMissing(v, currentPath ? `${currentPath}.${k}` : k));
    }
    return out;
  }
  return out;
}

// Reserved for future use: load the canonical English string for a missing
// marker so the review pack can show reviewers what the source string is.
// Currently computed inline from the marker; left here as a stable extension
// point so reviewer tooling can be written against it.
// eslint-disable-next-line no-unused-vars
function loadCanonical(_locale, _namespace) {
  return null;
}

function main() {
  if (!fs.existsSync(RESOURCES_ROOT)) {
    console.error(`[generate:i18n-review-pack] FAIL — resources root not found: ${RESOURCES_ROOT}`);
    process.exit(1);
  }
  fs.mkdirSync(path.join(REVIEW_PACK_ROOT, "PER-LOCALE"), { recursive: true });

  const locales = listLocales();
  if (!locales.includes(EN_US)) {
    console.error(`[generate:i18n-review-pack] FAIL — en-US catalog missing at ${RESOURCES_ROOT}/${EN_US}`);
    process.exit(1);
  }

  const namespaces = listNamespaces(EN_US);
  const inventory = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    description:
      "Per-locale, per-namespace list of __MISSING__:… placeholders that qualified native-language reviewers must replace in src/i18n/resources/<locale>/<namespace>.json. Generated by scripts/generate-i18n-review-pack.cjs — do NOT hand-edit this file; regenerate after any new placeholder is added to the catalogs.",
    locales: {},
    summary: { totalPlaceholders: 0, perLocale: {}, perNamespace: {} },
  };

  for (const locale of locales) {
    if (locale === EN_US) {
      inventory.locales[locale] = {
        status: "canonical",
        namespaces: Object.fromEntries(
          namespaces.map((ns) => [ns, { placeholders: [], total: 0 }]),
        ),
      };
      continue;
    }

    const localeDir = path.join(RESOURCES_ROOT, locale);
    const localeEntry = {
      status: "first-pass-machine",
      reviewer: null,
      reviewedAt: null,
      namespaces: {},
    };

    let localeTotal = 0;

    for (const ns of namespaces) {
      const file = path.join(localeDir, `${ns}.json`);
      if (!fs.existsSync(file)) {
        localeEntry.namespaces[ns] = { placeholders: [], total: 0, missing: true };
        continue;
      }
      const parsed = readJsonSafe(file);
      if (!parsed.ok) {
        console.error(`[generate:i18n-review-pack] FAIL — ${file}: ${parsed.error}`);
        process.exit(1);
      }
      const missing = findMissing(parsed.value);
      localeEntry.namespaces[ns] = {
        placeholders: missing.map((m) => ({
          key: m.path,
          marker: m.marker,
        })),
        total: missing.length,
      };
      localeTotal += missing.length;
      inventory.summary.perNamespace[ns] = (inventory.summary.perNamespace[ns] || 0) + missing.length;
    }

    localeEntry.total = localeTotal;
    inventory.locales[locale] = localeEntry;
    inventory.summary.perLocale[locale] = localeTotal;
    inventory.summary.totalPlaceholders += localeTotal;
  }

  const inventoryPath = path.join(REVIEW_PACK_ROOT, "PLACEHOLDER-INVENTORY.json");
  fs.writeFileSync(inventoryPath, JSON.stringify(inventory, null, 2) + "\n", "utf8");
  console.log(
    `[generate:i18n-review-pack] wrote ${inventoryPath} (${inventory.summary.totalPlaceholders} placeholders across ${Object.keys(inventory.locales).length - 1} non-English locales)`,
  );

  // Per-locale review pack files.
  for (const locale of Object.keys(inventory.locales)) {
    if (locale === EN_US) continue;
    const entry = inventory.locales[locale];
    const perLocalePath = path.join(REVIEW_PACK_ROOT, "PER-LOCALE", `${locale}.md`);
    const lines = [];
    lines.push(`# Native-language review pack — ${locale}`);
    lines.push("");
    lines.push(
      "> Generated by `scripts/generate-i18n-review-pack.cjs`. Do NOT hand-edit — regenerate after any new placeholder is added to the catalogs.",
    );
    lines.push("");
    lines.push("## Status");
    lines.push("");
    lines.push(`- **Status:** \`${entry.status}\``);
    lines.push(`- **Reviewer:** ${entry.reviewer || "(unassigned — see docs/i18n/native-review-status.json)"}`);
    lines.push(`- **Reviewed at:** ${entry.reviewedAt || "(never)"}`);
    lines.push(`- **Total placeholders to translate:** ${entry.total}`);
    lines.push("");
    lines.push("## How to use this pack");
    lines.push("");
    lines.push(
      "1. Open `src/i18n/resources/" +
        locale +
        "/<namespace>.json` for each namespace listed below.",
    );
    lines.push(
      "2. For every entry with a `\"__MISSING__:<key>\"` value, replace the value with the qualified native translation. Preserve any interpolation variables such as `{{name}}`.",
    );
    lines.push(
      "3. Do NOT mechanically translate via a machine-translation service — the per-locale `__MISSING__` markers are already machine translations, and the project policy (see `docs/i18n/native-review-status.json`) requires a qualified human reviewer.",
    );
    lines.push(
      "4. After translating, update `docs/i18n/native-review-status.json`: set this locale's `status` to `human-reviewed`, add your name to `reviewer`, and set `reviewedAt` to today's ISO-8601 date.",
    );
    lines.push(
      "5. Run `npm run verify:i18n-review-status` to confirm the catalogs and the status file agree.",
    );
    lines.push("");
    lines.push("## Placeholders by namespace");
    lines.push("");

    for (const ns of Object.keys(entry.namespaces)) {
      const nsEntry = entry.namespaces[ns];
      lines.push(`### ${ns} (${nsEntry.total})`);
      lines.push("");
      if (nsEntry.missing) {
        lines.push("**WARNING:** this namespace's catalog is missing entirely for `" + locale + "`.");
        lines.push("");
        continue;
      }
      if (nsEntry.placeholders.length === 0) {
        lines.push("- (none — this namespace is fully translated for `" + locale + "`)");
        lines.push("");
        continue;
      }
      lines.push("| JSON key | Placeholder marker |");
      lines.push("|---|---|");
      for (const p of nsEntry.placeholders) {
        lines.push(`| \`${p.key}\` | \`${p.marker.replace(/\|/g, "\\|")}\` |`);
      }
      lines.push("");
    }

    lines.push("## Reviewer checklist");
    lines.push("");
    lines.push(
      "- [ ] All `__MISSING__:` markers in this locale's namespaces are replaced with qualified translations.",
    );
    lines.push("- [ ] Interpolation variables (e.g. `{{name}}`, `{{limit}}`) are preserved verbatim.");
    lines.push("- [ ] Long-copy strings do not overflow the layout for the canonical viewports.");
    lines.push("- [ ] Plurals, gender, and RTL (where applicable) are correct.");
    lines.push("- [ ] Locale-appropriate number/date/currency formatting is used.");
    lines.push("- [ ] `docs/i18n/native-review-status.json` updated for this locale.");
    lines.push("- [ ] `npm run verify:i18n-review-status` exits 0.");
    lines.push("");

    fs.writeFileSync(perLocalePath, lines.join("\n"), "utf8");
  }

  console.log(`[generate:i18n-review-pack] wrote ${Object.keys(inventory.locales).length - 1} per-locale review pack files under ${REVIEW_PACK_ROOT}/PER-LOCALE/`);
}

main();
